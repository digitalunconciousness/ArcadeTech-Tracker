INVOICE_FROZEN = """
CREATE FUNCTION invoice_frozen() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    taxable_sum numeric;
    other_sum numeric;
    line_count integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'draft' THEN RETURN OLD; END IF;
        RAISE EXCEPTION 'invoice % is issued and can''t be deleted (void it)', OLD.number
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.status = 'draft' THEN
        IF NEW.status = 'draft' THEN RETURN NEW; END IF;
        IF NEW.status <> 'issued' THEN
            RAISE EXCEPTION 'a draft invoice can only be issued'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        SELECT coalesce(sum(line_total) FILTER (WHERE taxable), 0),
               coalesce(sum(line_total) FILTER (WHERE NOT taxable), 0), count(*)
          INTO taxable_sum, other_sum, line_count
          FROM invoice_line WHERE invoice_id = NEW.id;
        IF line_count = 0 THEN
            RAISE EXCEPTION 'invoice % has no lines', NEW.number
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF taxable_sum <> NEW.subtotal_taxable OR other_sum <> NEW.subtotal_nontaxable THEN
            RAISE EXCEPTION 'invoice % subtotals (% taxable, % not) don''t match its lines (%, %)',
                NEW.number, NEW.subtotal_taxable, NEW.subtotal_nontaxable, taxable_sum, other_sum
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.tax_status = 'collected' AND NEW.subtotal_taxable > 0 AND NEW.tax IS DISTINCT FROM
           round(NEW.subtotal_taxable * (NEW.tax_jurisdiction ->> 'combined_rate')::numeric, 2) THEN
            RAISE EXCEPTION 'invoice % tax % isn''t its taxable subtotal at the frozen rate',
                NEW.number, NEW.tax USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.status = 'void' THEN
        RAISE EXCEPTION 'invoice % is void and can''t change', OLD.number
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NEW.status = 'draft'
       OR (to_jsonb(NEW) - 'status' - 'amount_paid' - 'balance' - 'void_reason' - 'voided_at'
               - 'voided_by' - 'updated_at')
          IS DISTINCT FROM (to_jsonb(OLD) - 'status' - 'amount_paid' - 'balance' - 'void_reason'
               - 'voided_at' - 'voided_by' - 'updated_at') THEN
        RAISE EXCEPTION 'invoice % is issued: it can''t change (void it, or issue a credit memo)',
            OLD.number USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END $$
"""

INVOICE_LINE_FROZEN = """
CREATE FUNCTION invoice_line_frozen() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    parent_status text;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        SELECT status INTO parent_status FROM invoice WHERE id = OLD.invoice_id FOR SHARE;
        IF parent_status IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION 'invoice line % is on an issued invoice and can''t change', OLD.id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        SELECT status INTO parent_status FROM invoice WHERE id = NEW.invoice_id FOR SHARE;
        IF parent_status IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION 'invoice % is issued: its lines can''t change', NEW.invoice_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$
"""

WO_LINE_BILLED_GUARD = """
CREATE FUNCTION wo_line_billed_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    inv_status text;
    inv_number text;
BEGIN
    IF OLD.invoice_id IS NULL THEN
        IF TG_OP = 'UPDATE' AND NEW.invoice_id IS NOT NULL THEN
            SELECT status INTO inv_status FROM invoice WHERE id = NEW.invoice_id FOR SHARE;
            IF inv_status IS DISTINCT FROM 'draft' THEN
                RAISE EXCEPTION 'work order line % can only be put on a draft invoice', OLD.id
                    USING ERRCODE = 'integrity_constraint_violation';
            END IF;
        END IF;
        IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
        RETURN NEW;
    END IF;
    SELECT status, number INTO inv_status, inv_number FROM invoice
     WHERE id = OLD.invoice_id FOR SHARE;
    IF inv_status = 'draft' THEN
        IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND inv_status = 'void' AND NEW.invoice_id IS NULL
       AND (to_jsonb(NEW) - 'invoice_id' - 'updated_at')
           = (to_jsonb(OLD) - 'invoice_id' - 'updated_at') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'work order line % is billed on % and can''t change (void the invoice first)',
        OLD.id, inv_number USING ERRCODE = 'integrity_constraint_violation';
END $$
"""

