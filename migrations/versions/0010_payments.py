PAYMENT_GUARD = f"""
CREATE FUNCTION payment_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    src record;
    left_over numeric;
BEGIN
    PERFORM 1 FROM customer WHERE id = NEW.customer_id FOR UPDATE;
    IF NEW.kind = 'receipt' THEN
        IF NEW.estimate_id IS NOT NULL AND NOT EXISTS (
                SELECT 1 FROM estimate WHERE id = NEW.estimate_id
                AND customer_id = NEW.customer_id) THEN
            RAISE EXCEPTION 'estimate % is another customer''s', NEW.estimate_id {ERR};
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.kind = 'reversal' THEN
        SELECT * INTO src FROM payment WHERE id = NEW.reverses_payment_id;
        IF src.kind IS DISTINCT FROM 'receipt' OR src.customer_id <> NEW.customer_id THEN
            RAISE EXCEPTION 'only a payment received from this customer can be reversed' {ERR};
        END IF;
        IF NEW.amount <> -src.amount THEN
            RAISE EXCEPTION 'a reversal undoes the whole payment: %', -src.amount {ERR};
        END IF;
        IF EXISTS (SELECT 1 FROM payment WHERE refund_of_payment_id = src.id) THEN
            RAISE EXCEPTION 'part of payment % was refunded, so it can''t be reversed', src.id
                {ERR};
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.refund_of_payment_id IS NOT NULL THEN
        SELECT * INTO src FROM payment WHERE id = NEW.refund_of_payment_id;
        IF src.kind IS DISTINCT FROM 'receipt' OR src.customer_id <> NEW.customer_id THEN
            RAISE EXCEPTION 'a refund comes out of a payment this customer made' {ERR};
        END IF;
        IF EXISTS (SELECT 1 FROM payment WHERE reverses_payment_id = src.id) THEN
            RAISE EXCEPTION 'payment % was reversed: there is nothing to refund', src.id {ERR};
        END IF;
        left_over := src.amount
            - coalesce((SELECT sum(amount) FROM payment_allocation WHERE payment_id = src.id), 0)
            + coalesce((SELECT sum(amount) FROM payment WHERE refund_of_payment_id = src.id), 0);
    ELSE
        SELECT * INTO src FROM credit_memo WHERE id = NEW.refund_of_credit_memo_id;
        IF src.status IS DISTINCT FROM 'issued' OR src.customer_id <> NEW.customer_id THEN
            RAISE EXCEPTION 'a refund comes out of an issued credit memo of this customer' {ERR};
        END IF;
        left_over := src.total
            - coalesce((SELECT sum(amount) FROM payment_allocation
                        WHERE credit_memo_id = src.id), 0)
            + coalesce((SELECT sum(amount) FROM payment
                        WHERE refund_of_credit_memo_id = src.id), 0);
    END IF;
    IF -NEW.amount > left_over THEN
        RAISE EXCEPTION 'only % of it is left to refund', left_over {ERR};
    END IF;
    RETURN NEW;
END $$
"""

PAYMENT_REVERSAL_COMPLETE = f"""
CREATE FUNCTION payment_reversal_complete() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    applied numeric;
    taken_back numeric;
BEGIN
    SELECT coalesce(sum(amount), 0) INTO applied FROM payment_allocation
     WHERE payment_id = NEW.reverses_payment_id;
    SELECT coalesce(sum(amount), 0) INTO taken_back FROM payment_allocation
     WHERE payment_id = NEW.id;
    IF applied + taken_back <> 0 THEN
        RAISE EXCEPTION 'reversal % must take back all % that payment % applied to invoices',
            NEW.id, applied, NEW.reverses_payment_id {ERR};
    END IF;
    RETURN NULL;
END $$
"""

ALLOCATION_GUARD = f"""
CREATE FUNCTION allocation_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    inv record;
    owner_id integer;
    src_customer integer;
    src_kind text;
    src_amount numeric;
    reversed_of integer;
    used numeric;
    applied numeric;
BEGIN
    SELECT customer_id INTO owner_id FROM invoice WHERE id = NEW.invoice_id;
    PERFORM 1 FROM customer WHERE id = owner_id FOR UPDATE;
    SELECT id, number, customer_id, status, balance INTO inv FROM invoice
     WHERE id = NEW.invoice_id FOR UPDATE;
    IF NEW.payment_id IS NOT NULL THEN
        SELECT customer_id, kind, amount, reverses_payment_id
          INTO src_customer, src_kind, src_amount, reversed_of
          FROM payment WHERE id = NEW.payment_id;
    ELSE
        SELECT customer_id, CASE WHEN status = 'issued' THEN 'credit_memo' ELSE 'draft' END, total
          INTO src_customer, src_kind, src_amount
          FROM credit_memo WHERE id = NEW.credit_memo_id;
    END IF;
    IF src_customer IS DISTINCT FROM inv.customer_id THEN
        RAISE EXCEPTION 'that money belongs to a different customer than invoice %', inv.number
            {ERR};
    END IF;
    IF src_kind = 'reversal' THEN
        IF NEW.amount > 0 OR inv.status NOT IN ('issued', 'partially_paid', 'paid') THEN
            RAISE EXCEPTION 'a reversal only takes money back off an issued invoice' {ERR};
        END IF;
        SELECT coalesce(sum(amount), 0) INTO applied FROM payment_allocation
         WHERE invoice_id = NEW.invoice_id AND payment_id IN (reversed_of, NEW.payment_id);
        IF applied + NEW.amount < 0 THEN
            RAISE EXCEPTION 'takes back more than payment % applied to invoice %', reversed_of,
                inv.number {ERR};
        END IF;
        RETURN NEW;
    END IF;
    IF src_kind NOT IN ('receipt', 'credit_memo') THEN
        RAISE EXCEPTION 'only money received or an issued credit memo pays an invoice' {ERR};
    END IF;
    IF inv.status NOT IN ('issued', 'partially_paid') THEN
        RAISE EXCEPTION 'invoice % is %: there is nothing to pay', inv.number, inv.status {ERR};
    END IF;
    IF NEW.amount > inv.balance THEN
        RAISE EXCEPTION 'invoice % has % left to pay, not %', inv.number, inv.balance,
            NEW.amount {ERR};
    END IF;
    IF NEW.payment_id IS NOT NULL THEN
        IF EXISTS (SELECT 1 FROM payment WHERE reverses_payment_id = NEW.payment_id) THEN
            RAISE EXCEPTION 'payment % was reversed', NEW.payment_id {ERR};
        END IF;
        used := coalesce((SELECT sum(amount) FROM payment_allocation
                          WHERE payment_id = NEW.payment_id), 0)
              - coalesce((SELECT sum(amount) FROM payment
                          WHERE refund_of_payment_id = NEW.payment_id), 0);
    ELSE
        used := coalesce((SELECT sum(amount) FROM payment_allocation
                          WHERE credit_memo_id = NEW.credit_memo_id), 0)
              - coalesce((SELECT sum(amount) FROM payment
                          WHERE refund_of_credit_memo_id = NEW.credit_memo_id), 0);
    END IF;
    IF used + NEW.amount > src_amount THEN
        RAISE EXCEPTION 'only % of it is left to apply', src_amount - used {ERR};
    END IF;
    RETURN NEW;
END $$
"""

ALLOCATION_APPLY = """
CREATE FUNCTION allocation_apply() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE invoice i
       SET amount_paid = s.paid, amount_credited = s.credited,
           balance = i.total - s.paid - s.credited,
           status = CASE WHEN i.total - s.paid - s.credited = 0 THEN 'paid'
                         WHEN s.paid + s.credited > 0 THEN 'partially_paid'
                         ELSE 'issued' END
      FROM (SELECT coalesce(sum(amount) FILTER (WHERE payment_id IS NOT NULL), 0) AS paid,
                   coalesce(sum(amount) FILTER (WHERE credit_memo_id IS NOT NULL), 0) AS credited
              FROM payment_allocation WHERE invoice_id = NEW.invoice_id) s
     WHERE i.id = NEW.invoice_id;
    RETURN NULL;
END $$
"""

