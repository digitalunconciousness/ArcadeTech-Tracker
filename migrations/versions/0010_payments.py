INVOICE_FROZEN = f"""
CREATE OR REPLACE FUNCTION invoice_frozen() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    taxable_sum numeric;
    other_sum numeric;
    line_count integer;
    paid_sum numeric;
    credited_sum numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'draft' THEN RETURN OLD; END IF;
        RAISE EXCEPTION 'invoice % is issued and can''t be deleted (void it)', OLD.number {ERR};
    END IF;
    IF OLD.status = 'draft' THEN
        IF NEW.status = 'draft' THEN RETURN NEW; END IF;
        IF NEW.status <> 'issued' THEN
            RAISE EXCEPTION 'a draft invoice can only be issued' {ERR};
        END IF;
        IF NEW.amount_paid <> 0 OR NEW.amount_credited <> 0 THEN
            RAISE EXCEPTION 'nothing is paid on an invoice before it is issued' {ERR};
        END IF;
        SELECT coalesce(sum(line_total) FILTER (WHERE taxable), 0),
               coalesce(sum(line_total) FILTER (WHERE NOT taxable), 0), count(*)
          INTO taxable_sum, other_sum, line_count
          FROM invoice_line WHERE invoice_id = NEW.id;
        IF line_count = 0 THEN
            RAISE EXCEPTION 'invoice % has no lines', NEW.number {ERR};
        END IF;
        IF taxable_sum <> NEW.subtotal_taxable OR other_sum <> NEW.subtotal_nontaxable THEN
            RAISE EXCEPTION 'invoice % subtotals (% taxable, % not) don''t match its lines (%, %)',
                NEW.number, NEW.subtotal_taxable, NEW.subtotal_nontaxable, taxable_sum, other_sum
                {ERR};
        END IF;
        IF NEW.tax_status = 'collected' AND NEW.subtotal_taxable > 0 AND NEW.tax IS DISTINCT FROM
           round(NEW.subtotal_taxable * (NEW.tax_jurisdiction ->> 'combined_rate')::numeric, 2) THEN
            RAISE EXCEPTION 'invoice % tax % isn''t its taxable subtotal at the frozen rate',
                NEW.number, NEW.tax {ERR};
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.status = 'void' THEN
        RAISE EXCEPTION 'invoice % is void and can''t change', OLD.number {ERR};
    END IF;
    IF NEW.status = 'draft'
       OR (to_jsonb(NEW) - {FROZEN_COLUMNS}) IS DISTINCT FROM (to_jsonb(OLD) - {FROZEN_COLUMNS}) THEN
        RAISE EXCEPTION 'invoice % is issued: it can''t change (void it, or issue a credit memo)',
            OLD.number {ERR};
    END IF;
    SELECT coalesce(sum(amount) FILTER (WHERE payment_id IS NOT NULL), 0),
           coalesce(sum(amount) FILTER (WHERE credit_memo_id IS NOT NULL), 0)
      INTO paid_sum, credited_sum FROM payment_allocation WHERE invoice_id = NEW.id;
    IF NEW.amount_paid <> paid_sum OR NEW.amount_credited <> credited_sum THEN
        RAISE EXCEPTION 'invoice % paid and credited must be what is applied to it (%, %)',
            OLD.number, paid_sum, credited_sum {ERR};
    END IF;
    IF NEW.status = 'void' AND (paid_sum <> 0 OR credited_sum <> 0) THEN
        RAISE EXCEPTION 'invoice % has payments or credits applied: it can''t be voided',
            OLD.number {ERR};
    END IF;
    RETURN NEW;
END $$
"""

