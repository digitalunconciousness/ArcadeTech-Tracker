CREDIT_MEMO_FROZEN = f"""
CREATE FUNCTION credit_memo_frozen() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    taxable_sum numeric;
    other_sum numeric;
    line_count integer;
    billed numeric;
    credited numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'draft' THEN RETURN OLD; END IF;
        RAISE EXCEPTION 'credit memo % is issued and can''t be deleted', OLD.number {ERR};
    END IF;
    IF OLD.status = 'issued' THEN
        RAISE EXCEPTION 'credit memo % is issued and can''t change', OLD.number {ERR};
    END IF;
    IF NEW.status = 'draft' THEN RETURN NEW; END IF;
    SELECT coalesce(sum(line_total) FILTER (WHERE taxable), 0),
           coalesce(sum(line_total) FILTER (WHERE NOT taxable), 0), count(*)
      INTO taxable_sum, other_sum, line_count
      FROM credit_memo_line WHERE credit_memo_id = NEW.id;
    IF line_count = 0 OR NEW.total <= 0 THEN
        RAISE EXCEPTION 'credit memo % credits nothing', NEW.number {ERR};
    END IF;
    IF taxable_sum <> NEW.subtotal_taxable OR other_sum <> NEW.subtotal_nontaxable THEN
        RAISE EXCEPTION 'credit memo % subtotals don''t match its lines', NEW.number {ERR};
    END IF;
    IF NEW.tax_rate IS NOT NULL AND NEW.tax <> round(NEW.subtotal_taxable * NEW.tax_rate, 2) THEN
        RAISE EXCEPTION 'credit memo % tax isn''t its taxable subtotal at the invoice''s rate',
            NEW.number {ERR};
    END IF;
    SELECT total INTO billed FROM invoice
     WHERE id = NEW.invoice_id AND customer_id = NEW.customer_id
       AND status NOT IN ('draft', 'void') FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'a credit memo goes against an issued invoice of the same customer' {ERR};
    END IF;
    SELECT coalesce(sum(total), 0) INTO credited FROM credit_memo
     WHERE invoice_id = NEW.invoice_id AND status = 'issued' AND id <> NEW.id;
    IF credited + NEW.total > billed THEN
        RAISE EXCEPTION 'credits on that invoice would come to more than it billed (% of %)',
            credited + NEW.total, billed {ERR};
    END IF;
    RETURN NEW;
END $$
"""

